            "\n",
            "NEGATION_WORDS = {\"not\", \"no\", \"never\", \"cannot\", \"cant\", \"n't\", \"neither\", \"nor\", \"without\", \"barely\"}\n",
            "CLAUSE_PUNCT = {\".\", \",\", \"!\", \"?\", \";\", \":\", \"-\", \"but\", \"however\", \"although\", \"yet\"}\n",
            "\n",
            "def clean_tweet_text(text: str) -> str:\n",
            "    if not isinstance(text, str): return \"\"\n",
            "    t = re.sub(r'https?://\\S+|www\\.\\S+', '', text) # Remove URLs\n",
            "    t = re.sub(r'@\\w+', '', t)                      # Remove @mentions\n",
            "    t = re.sub(r'#(\\w+)', r'\\1', t)                 # Keep hashtag words\n",
            "    t = re.sub(r'\\s+', ' ', t).strip()             # Normalize whitespace\n",
            "    return t\n",
            "\n",
            "def apply_negation_tagging(text: str, max_window: int = 3) -> str:\n",
            "    if not isinstance(text, str): return \"\"\n",
            "    t_lower = text.lower()\n",
            "    for pat, rep in CONTRACTIONS.items():\n",
            "        t_lower = re.sub(pat, rep, t_lower)\n",
            "    tokens = re.findall(r'\\w+|[^\\w\\s]', t_lower, re.UNICODE)\n",
            "    out = []\n",
            "    countdown = 0\n",
            "    for tok in tokens:\n",
            "        if tok in NEGATION_WORDS:\n",
            "            out.append(tok)\n",
            "            countdown = max_window\n",
            "            continue\n",
            "        if tok in CLAUSE_PUNCT:\n",
            "            out.append(tok)\n",
            "            countdown = 0\n",
            "            continue\n",
            "        if countdown > 0 and tok.isalnum():\n",
            "            out.append(f\"{tok}_NEG\")\n",
            "            countdown -= 1\n",
            "        else:\n",
            "            out.append(tok)\n",
            "    return \" \".join(out)\n",
            "\n",
            "class StandaloneEmotionLabeler:\n",
            "    def __init__(self):\n",
            "        self.vader = SentimentIntensityAnalyzer()\n",
